'''
OPERATORS:
Operators in Python are special symbols or keywords 
that enable the performance of various operations on data

TYPES
1.Arithmetic operators:
Arithmetic operators are used with numeric values to perform 
common mathematical operations:
e.g +,-, /,*, **, //

2.Assignment operators:
Assignment operators are used to assign values to variables
e.g:
=, +=, -=, *=, /=

3.Comparison operators 
Comparison operators are used to compare two values:
e.g:
Operator	Name	
==	Equal	
!=	Not equal	
>	Greater than	
<	Less than	
>=	Greater than or equal to
<=	Less than or equal to	

4.Logical operators:
Logical operators are used to combine conditional statements:
e.g:
and, or, not
5.Identity operators
Identity operators are used to compare the objects, not if they are equal, but 
if they are actually the same object, with the same memory location:
e.g: 
is, is not

6.Membership operators
Membership operators are used to test if a sequence is presented in an object:
e.g:
in, not in

'''

